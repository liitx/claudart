// families_topology_test.dart — the topological families of the code, and
// proof the generated doc is current.
//
// docs/topology/families.md puts every file of lib/ and bin/ in one cell of
// StateRole x ReachLayer (test/helpers/topology_family.dart). It fails when
// the code and the checked-in doc disagree:
//
//   make topology        # UPDATE_TOPOLOGY=1 rewrites the doc

import 'dart:io';

import 'package:test/test.dart';

import '../helpers/event_usage.dart';
import '../helpers/topology_family.dart';

const _docPath = 'docs/topology/families.md';
const _updateEnvVar = 'UPDATE_TOPOLOGY';
const _updateEnabledValue = '1';
const _binEntry = 'bin/claudart.dart';
const _noFiles = '—';

/// A source that lands in each [StateRole], written in the code shape the
/// role's own pattern looks for; the complement needs no such shape.
const _roleSamples = <StateRole, String>{
  StateRole.drivesState: 'void f() => applyHandoffEvent();',
  StateRole.observesState: 'bool f(HandoffStatus s) => true;',
  StateRole.untouched: 'int f() => 1;',
};

/// The same for each [ReachLayer].
const _reachSamples = <ReachLayer, String>{
  ReachLayer.pure: 'int f() => 1;',
  ReachLayer.fileSeam: 'void f(FileIO io) {}',
  ReachLayer.workspaceBound: 'void f() => Registry.load();',
  ReachLayer.processBound: 'void f() => detectGitContext();',
};

Map<String, String> _sources() => {
      ...readLibSources(),
      _binEntry: File(_binEntry).readAsStringSync(),
    };

int _count(
  Map<TopologyFamily, List<String>> groups,
  StateRole role,
  ReachLayer layer,
) =>
    groups[(role: role, reach: layer)]?.length ?? 0;

String renderFamilies(Map<String, String> sources) {
  final groups = groupByFamily(sources);
  const layers = ReachLayer.values;
  return [
    '# Topological families',
    '',
    '> Generated by `make topology` from the code. Do not edit by hand: a '
        'test fails when this file and the code disagree.',
    '',
    'A family is a cell of two axes read from what a file\'s code does '
        '(`test/helpers/topology_family.dart`): the state role (does it emit '
        'a handoff event, only read a status, or neither) and the farthest '
        'layer it reaches. A file whose code matches no portal falls in the '
        'complement, `untouched x pure`. A name that is only declared in a '
        'file also matches, so the owner of a portal sits beside its users.',
    '',
    '| role \\ reach | ${layers.map((l) => l.name).join(' | ')} |',
    '|${'---|' * (layers.length + 1)}',
    for (final role in StateRole.values)
      '| ${role.name} | '
          '${layers.map((l) => _count(groups, role, l)).join(' | ')} |',
    '',
    for (final role in StateRole.values)
      for (final layer in layers) ...[
        '## ${role.name} x ${layer.name}',
        '',
        groups[(role: role, reach: layer)]?.map((f) => '- `$f`').join('\n') ??
            _noFiles,
        '',
      ],
  ].join('\n');
}

void main() {
  group('$StateRole.of', () {
    for (final role in StateRole.values) {
      test('${role.name} is found in its own code shape', () {
        expect(StateRole.of(_roleSamples[role]!), role);
      });
    }

    test('drivesState outranks observesState', () {
      expect(
        StateRole.of('applyHandoffEvent(); HandoffStatus s;'),
        StateRole.drivesState,
      );
    });
  });

  group('$ReachLayer.of', () {
    for (final layer in ReachLayer.values) {
      test('${layer.name} is found in its own code shape', () {
        expect(ReachLayer.of(_reachSamples[layer]!), layer);
      });
    }

    test('the farthest layer wins', () {
      expect(
        ReachLayer.of('FileIO io; Registry.load(); detectGitContext();'),
        ReachLayer.processBound,
      );
    });
  });

  group('topologyFamilyOf', () {
    test('ignores a portal named only in a comment', () {
      expect(
        topologyFamilyOf('// Registry.load( detectGitContext(\nint f() => 1;'),
        (role: StateRole.untouched, reach: ReachLayer.pure),
      );
    });

    test('puts every file in exactly one family', () {
      final sources = _sources();
      final grouped = groupByFamily(sources).values.expand((f) => f).toList();
      expect(grouped..sort(), sources.keys.toList()..sort());
    });
  });

  group('the checked-in doc', () {
    test('docs/topology/families.md matches the code', () {
      final rendered = renderFamilies(_sources());
      if (Platform.environment[_updateEnvVar] == _updateEnabledValue) {
        File(_docPath)
          ..createSync(recursive: true)
          ..writeAsStringSync(rendered);
      }
      expect(
        File(_docPath).readAsStringSync(),
        rendered,
        reason: 'A file changed family: run `make topology` and review the '
            'diff.',
      );
    });
  });
}
