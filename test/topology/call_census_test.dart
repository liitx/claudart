// call_census_test.dart — what each lifecycle step reads and writes, counted.
//
// Runs every lifecycle scenario step (test/conformance/lifecycle_scenarios.dart)
// against a CountingFileIO and writes the per-step file calls to
// docs/topology/call_census.md. Redundancy and unrecorded writes are read off
// the table instead of argued. It fails when the doc and the code disagree:
//
//   make topology        # UPDATE_TOPOLOGY=1 rewrites the doc
//
// Only the FileIO seam is observed. A process spawned outside the injected
// runner is invisible here; those are measured separately (see the stage 0.3
// record in docs/methodical_refactor.md).

import 'dart:io';

import 'package:test/test.dart';

import '../conformance/lifecycle_scenarios.dart';
import '../helpers/call_census.dart';
import '../helpers/counting_file_io.dart';

const _docPath = 'docs/topology/call_census.md';
const _updateEnvVar = 'UPDATE_TOPOLOGY';
const _updateEnabledValue = '1';
const _noCalls = '—';

/// One cell: the operations that happened on [file], each as its first letter
/// and count (`read` as `r2`), or [_noCalls].
String census(List<FileCall> calls, CensusFile file) {
  final cells = [
    for (final operation in FileOperation.values)
      if (countCalls(calls, file, operation) > 0)
        '${operation.name[0]}${countCalls(calls, file, operation)}',
  ];
  return cells.isEmpty ? _noCalls : cells.join(' ');
}

/// The calls each step of each scenario made, in scenario order.
Future<List<({String scenario, String step, List<FileCall> calls})>>
    measureLifecycle() async {
  final rows = <({String scenario, String step, List<FileCall> calls})>[];
  for (final scenario in lifecycleScenarios().entries) {
    final io = CountingFileIO.from(freshLifecycleIo());
    io.takeCalls();
    for (final step in scenario.value) {
      await quietly(() => step.run(io));
      rows.add((
        scenario: scenario.key,
        step: step.name,
        calls: io.takeCalls(),
      ));
    }
  }
  return rows;
}

String renderCallCensus(
  List<({String scenario, String step, List<FileCall> calls})> rows,
) {
  final header = '| scenario | step | '
      '${CensusFile.values.map((file) => file.name).join(' | ')} |';
  final divider = '|${'---|' * (CensusFile.values.length + 2)}';
  return [
    '# Call census',
    '',
    '> Generated by `make topology` from the code. Do not edit by hand: a '
        'test fails when this file and the code disagree.',
    '',
    'Each cell is the calls a lifecycle step made through the FileIO seam, '
        'by file kind: `r` read, `w` write, `a` append, `d` delete, with a '
        'count. Steps run with `projectRootOverride`, so git is not asked; '
        'processes are not observed here.',
    '',
    header,
    divider,
    for (final row in rows)
      '| ${row.scenario} | ${row.step} | '
          '${CensusFile.values.map((file) => census(row.calls, file)).join(' | ')} |',
    '',
  ].join('\n');
}

void main() {
  group('$CensusFile.of', () {
    for (final file in CensusFile.values.where((f) => f.fileName != null)) {
      test('${file.name} is found by its file name', () {
        expect(CensusFile.of('/any/dir/${file.fileName}'), file);
      });
    }

    test('a file nobody has named is other', () {
      expect(CensusFile.of('/any/dir/unnamed.txt'), CensusFile.other);
    });
  });

  group('$CountingFileIO', () {
    test('counts a read and still returns the content', () {
      final io = CountingFileIO.from(freshLifecycleIo());
      io.write('/x/handoff.md', 'body');
      io.takeCalls();
      expect(io.read('/x/handoff.md'), 'body');
      expect(io.calls, [(operation: FileOperation.read, path: '/x/handoff.md')]);
    });
  });

  group('the checked-in census', () {
    test('docs/topology/call_census.md matches the code', () async {
      final rendered = renderCallCensus(await measureLifecycle());
      if (Platform.environment[_updateEnvVar] == _updateEnabledValue) {
        File(_docPath)
          ..createSync(recursive: true)
          ..writeAsStringSync(rendered);
      }
      expect(File(_docPath).readAsStringSync(), rendered);
    });
  });
}
