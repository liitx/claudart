// matrix_consumers_test.dart — every decision table is decided with, and proof
// the generated doc is current.
//
// docs/topology/matrix_consumers.md lists each decision table of lib/ (a
// function whose enum result is chosen by a switch), who calls it, and whether
// a caller decides with the result or only shows it. A table nothing decides
// with can change while the program behaves the same, so tests of the table
// prove nothing about the program (gap T7). The rule below fails for any table
// in that state that is not named, with its reason, in [_notDecidedWith].
//
//   make topology        # UPDATE_TOPOLOGY=1 rewrites the doc

import 'dart:io';

import 'package:test/test.dart';

import '../../tool/proof_audit/providers.dart';
import '../helpers/event_usage.dart';
import '../helpers/matrix_consumers.dart';
import '../helpers/topology_family.dart';

const _docPath = 'docs/topology/matrix_consumers.md';
const _updateEnvVar = 'UPDATE_TOPOLOGY';
const _updateEnabledValue = '1';
const _binEntry = 'bin/claudart.dart';

/// Why a decision table has no decider in this package.
enum UndecidedReason {
  /// Another package decides with it: claudart exports it and the consumer is
  /// outside this repository.
  decidedByAnotherPackage,

  /// Nothing decides with it and the owner has not said what should; recorded
  /// as a gap in docs/methodical_refactor.md.
  decisionPending,
}

/// Decision tables nothing in this package decides with, and why. A table that
/// starts to drive behavior must be removed from here, so the list stays true.
const _notDecidedWith =
    <String, ({UndecidedReason reason, String evidence})>{
  'fromEvent': (
    reason: UndecidedReason.decidedByAnotherPackage,
    evidence: 'exported by lib/claudart.dart; zedup/lib/src/agent_flow/'
        'agent_flow_state.dart:217 sets a step status from it',
  ),
  'automaticClosureFor': (
    reason: UndecidedReason.decisionPending,
    evidence: 'gap T7: only status.dart reads it, to print a label; teardown '
        'decides from the evidence directly',
  ),
};

/// Decision tables the proof audit does not seed faults into yet. A table that
/// gains a provider must be removed from here, so the list stays true; a new
/// decision table fails until it is audited or named here.
const _notAuditedYet = {
  'stateOf',
  'settleLiveHandoff',
  'hue',
  'routeModel',
  'kind',
  'fromEvent',
  '_knowledgeTransferFindings',
};

Map<String, String> _sources() => {
      ...readLibSources(),
      _binEntry: File(_binEntry).readAsStringSync(),
    };

typedef _Row = ({
  DecisionTable table,
  List<Consumer> consumers,
  TableVerdict verdict,
});

List<_Row> _rows(Map<String, String> sources) {
  final tables = findDecisionTables(sources, enumNames(sources))
    ..sort((a, b) => '${a.file}:${a.line}'.compareTo('${b.file}:${b.line}'));
  return [
    for (final table in tables)
      (
        table: table,
        consumers: consumersOf(table, sources),
        verdict: verdictOf(
          consumersOf(table, sources),
          ambiguous: isAmbiguousGetter(table, sources),
        ),
      ),
  ];
}

bool _isUndecided(_Row row) =>
    row.verdict == TableVerdict.displayOnly ||
    row.verdict == TableVerdict.unconsumed;

String _cell(TopologyFamily family) => '${family.role.name} x ${family.reach.name}';

String renderMatrixConsumers(Map<String, String> sources) {
  final rows = _rows(sources);
  final out = StringBuffer()
    ..writeln('# Decision tables and who decides with them')
    ..writeln()
    ..writeln('> Generated by `make topology` from the code. Do not edit by hand: a '
        'test fails when this file and the code disagree.')
    ..writeln()
    ..writeln('A decision table is a function whose result is an enum value (or a '
        'list or set of them) chosen by a `switch`. A caller that only reads the '
        'result\'s `.label` or `.name`, or puts it in a message, is a display; one '
        'that branches on it or hands it on is a decider. A table with no decider '
        'can change while the program behaves the same (gap T7).')
    ..writeln()
    ..writeln('| Decision table | Returns | Family of its file | Deciders | Displays | Verdict |')
    ..writeln('|---|---|---|---|---|---|');
  for (final row in rows) {
    final family = topologyFamilyOf(sources[row.table.file]!);
    out.writeln('| `${row.table.name}` (`${row.table.file}:${row.table.line}`) | '
        '`${row.table.returns}` | ${_cell(family)} | '
        '${row.consumers.where((c) => c.kind == ConsumerKind.control).length} | '
        '${row.consumers.where((c) => c.kind == ConsumerKind.display).length} | '
        '${row.verdict.name} |');
  }

  final undecided = rows.where(_isUndecided).toList();
  out
    ..writeln()
    ..writeln('## Tables nothing decides with')
    ..writeln();
  if (undecided.isEmpty) {
    out.writeln('None.');
  }
  for (final row in undecided) {
    out.writeln('- `${row.table.name}` (${row.verdict.name}):');
    if (row.consumers.isEmpty) out.writeln('  - no caller');
    for (final consumer in row.consumers) {
      out.writeln('  - `${consumer.file}:${consumer.line}` `${consumer.text}`');
    }
  }

  final unattributed =
      rows.where((r) => r.verdict == TableVerdict.unattributed).toList();
  out
    ..writeln()
    ..writeln('## Getters whose readers cannot be told apart')
    ..writeln();
  if (unattributed.isEmpty) out.writeln('None.');
  for (final row in unattributed) {
    out.writeln('- `${row.table.name}` (`${row.table.file}:${row.table.line}`): '
        'another declaration shares the name, so a read of `.${row.table.name}` '
        'is not counted either way.');
  }

  final byFamily = groupByFamily(sources);
  final withTable = {for (final row in rows) row.table.file};
  out
    ..writeln()
    ..writeln('## Where the tables sit among the families')
    ..writeln()
    ..writeln('If the family of a file said whether it holds a decision table, '
        'every cell would be all tables or none. A cell with both shows the '
        'family cannot predict it, so the question "does something decide with '
        'this table" is not a family of its own but a perspective each table '
        'answers.')
    ..writeln()
    ..writeln('| Family | Files | Files holding a table |')
    ..writeln('|---|---|---|');
  final cells = byFamily.entries.toList()
    ..sort((a, b) => _cell(a.key).compareTo(_cell(b.key)));
  for (final entry in cells) {
    final holding = entry.value.where(withTable.contains).length;
    if (holding == 0) continue;
    out.writeln('| ${_cell(entry.key)} | ${entry.value.length} | $holding |');
  }
  return out.toString();
}

void main() {
  final sources = _sources();
  final rows = _rows(sources);

  group('the finder', () {
    const enums = {'Color', 'Mode'};

    List<String> found(String source) => [
          for (final table in findDecisionTables({'lib/a.dart': source}, enums))
            table.name,
        ];

    test('finds an enum result chosen by an expression switch', () {
      expect(found('Color paint(Mode mode) => switch (mode) {\n  _ => Color.red,\n};'),
          ['paint']);
    });

    test('finds an enum result chosen by a switch in a block body', () {
      expect(
        found('Color paint(Mode mode) {\n  final x = 1;\n  return switch (mode) {\n'
            '    _ => Color.red,\n  };\n}'),
        ['paint'],
      );
    });

    test('finds a list of enum values', () {
      expect(found('List<Color> all(Mode m) => switch (m) {\n  _ => [Color.red],\n};'),
          ['all']);
    });

    test('finds an enum getter chosen by a switch', () {
      expect(
        found('Color get shade => switch (this) {\n  _ => Color.red,\n};'),
        ['shade'],
      );
    });

    test('does not find a getter that returns something else', () {
      expect(found('String get shade => switch (this) {\n  _ => "x",\n};'), isEmpty);
    });

    test('does not find a function that returns something else', () {
      expect(found('String say(Mode m) => switch (m) {\n  _ => "x",\n};'), isEmpty);
    });

    test('does not find an enum result chosen without a switch', () {
      expect(found('Color pick(Mode m) => Color.red;'), isEmpty);
    });

    test('reads the line the table is declared on', () {
      final table = findDecisionTables({
        'lib/a.dart': '// a comment\n\nColor paint(Mode m) => switch (m) {\n  _ => Color.red,\n};',
      }, enums).single;
      expect(table.line, 3);
    });
  });

  group('classifying a caller', () {
    ConsumerKind kind(String line, String name) =>
        classifyConsumer(line, line.indexOf(name));

    test('reading the label is a display (the line that showed gap T7)', () {
      expect(
        kind("      'closure': automaticClosureFor(closureEvidence).label,",
            'automaticClosureFor'),
        ConsumerKind.display,
      );
    });

    test('reading the name is a display', () {
      expect(kind('final text = pick(x).name;', 'pick'), ConsumerKind.display);
    });

    test('inside a printed message is a display', () {
      expect(kind('print(describe(pick(x)));', 'pick'), ConsumerKind.display);
    });

    test('in a condition decides', () {
      expect(kind('if (pick(x) == Color.red) {', 'pick'), ConsumerKind.control);
    });

    test('in a switch decides', () {
      expect(kind('switch (pick(x)) {', 'pick'), ConsumerKind.control);
    });

    test('handed on to another call decides', () {
      expect(kind('run(pick(x));', 'pick'), ConsumerKind.control);
    });

    test('a null-safe read of the label is a display', () {
      expect(kind('final t = pick(x)?.label;', 'pick'), ConsumerKind.display);
    });

    test('a getter read for its label is a display', () {
      const line = 'final t = status.hue.label;';
      expect(
        classifyConsumer(line, line.indexOf('.hue'), getterName: 'hue'),
        ConsumerKind.display,
      );
    });

    test('a getter read in a condition decides', () {
      const line = 'if (event.kind == Kind.done) {';
      expect(
        classifyConsumer(line, line.indexOf('.kind'), getterName: 'kind'),
        ConsumerKind.control,
      );
    });
  });

  group('a new decision table', () {
    const definition = 'enum Mode { a, b }\n'
        'enum Action { go, stop }\n'
        'Action chooseAction(Mode mode) => switch (mode) {\n'
        '  Mode.a => Action.go,\n'
        '  Mode.b => Action.stop,\n'
        '};\n';

    TableVerdict verdictFor(String caller) {
      final all = {'lib/a.dart': definition, 'lib/b.dart': caller};
      final table =
          findDecisionTables(all, enumNames(all)).single;
      return verdictOf(consumersOf(table, all));
    }

    test('only shown in a message is caught as display only', () {
      expect(
        verdictFor('void f(Mode m) => print(chooseAction(m).label);'),
        TableVerdict.displayOnly,
      );
    });

    test('that nothing calls is caught as unconsumed', () {
      expect(verdictFor('void f() {}'), TableVerdict.unconsumed);
    });

    test('that a caller branches on drives', () {
      expect(
        verdictFor('void f(Mode m) {\n  if (chooseAction(m) == Action.go) {}\n}'),
        TableVerdict.drives,
      );
    });
  });

  group('the verdict', () {
    const display = (file: 'a', line: 1, text: 't', kind: ConsumerKind.display);
    const control = (file: 'a', line: 2, text: 't', kind: ConsumerKind.control);

    test('no caller is unconsumed', () {
      expect(verdictOf(const []), TableVerdict.unconsumed);
    });

    test('only displays is display only', () {
      expect(verdictOf(const [display, display]), TableVerdict.displayOnly);
    });

    test('a getter whose name is shared is not attributed either way', () {
      expect(
        verdictOf(const [display], ambiguous: true),
        TableVerdict.unattributed,
      );
    });

    test('one decider is enough to drive', () {
      expect(verdictOf(const [display, control]), TableVerdict.drives);
    });
  });

  group('decision tables', () {
    test('there are some, so the finder is not looking at nothing', () {
      expect(rows, isNotEmpty);
    });

    test('the transition table is found and driven by commands', () {
      final after = rows.firstWhere((r) => r.table.name == 'after');
      expect(after.verdict, TableVerdict.drives);
    });

    test('nothing but what is named here is left undecided', () {
      final undecided = {
        for (final row in rows)
          if (_isUndecided(row)) row.table.name,
      };
      expect(undecided, _notDecidedWith.keys.toSet(),
          reason: 'a table nothing decides with must be wired into the behavior '
              'it describes, or named in _notDecidedWith with the reason; a name '
              'there that is now driven must be removed');
    });

    test('a table decided with by another package is exported for it', () {
      final barrel = sources['lib/claudart.dart']!;
      for (final entry in _notDecidedWith.entries) {
        if (entry.value.reason != UndecidedReason.decidedByAnotherPackage) continue;
        final table = rows.firstWhere((r) => r.table.name == entry.key).table;
        expect(
          barrel,
          contains("export '${table.file.replaceFirst('lib/', '')}';"),
          reason: '${entry.key} is not exported, so no other package can use it',
        );
      }
    });

    test('every decision table is audited by a provider or named as not yet', () {
      final audited = {
        for (final provider in auditProviders) ...provider.coveredTables,
      };
      final unaudited = {
        for (final row in rows)
          if (!audited.contains(row.table.name)) row.table.name,
      };
      expect(unaudited, _notAuditedYet,
          reason: 'a decision table needs a provider in tool/proof_audit/ '
              '(coveredTables), or a name in _notAuditedYet; a name there that '
              'is now audited must be removed');
    });

    test('a provider covers only tables that exist', () {
      final names = {for (final row in rows) row.table.name};
      for (final provider in auditProviders) {
        for (final covered in provider.coveredTables) {
          expect(names, contains(covered),
              reason: '${provider.proof} names $covered, which is not a decision table');
        }
      }
    });

    test('the family of a file does not say whether it holds a decision table',
        () {
      final byFamily = groupByFamily(sources);
      final withTable = {for (final row in rows) row.table.file};
      final mixed = [
        for (final entry in byFamily.entries)
          if (entry.value.any(withTable.contains) &&
              entry.value.any((file) => !withTable.contains(file)))
            entry.key,
      ];
      expect(mixed, isNotEmpty);
    });
  });

  group('docs/topology/matrix_consumers.md', () {
    test('is current', () {
      final rendered = renderMatrixConsumers(sources);
      if (Platform.environment[_updateEnvVar] == _updateEnabledValue) {
        File(_docPath).writeAsStringSync(rendered);
      }
      expect(File(_docPath).readAsStringSync(), rendered);
    });
  });
}
