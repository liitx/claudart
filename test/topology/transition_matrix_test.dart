// transition_matrix_test.dart — which (status, event) cells real commands hit.
//
// Runs every lifecycle scenario (test/conformance/lifecycle_scenarios.dart)
// and reads the moves the commands logged to transitions.jsonl. Each of the
// HandoffStatus x HandoffEvent cells is then one of:
//   - legal and hit      `ok xN`  the table allows it and a command did it
//   - legal, never hit   `GAP`    nothing drives it: unproven by any scenario
//   - rejected, hit      `REJ xN` a command tried a move the table lacks
//   - rejected, not hit  `·`      the table forbids it and nothing tries it
// docs/topology/transition_matrix.md holds the matrix and fails when the code
// disagrees. The same scenarios run in every link state x dartrix on/off; the
// logged moves must be identical in all of them, which this test proves.
//
//   make topology        # UPDATE_TOPOLOGY=1 rewrites the doc

import 'dart:convert';
import 'dart:io';

import 'package:claudart/logging/log_file.dart';
import 'package:claudart/logging/logger.dart';
import 'package:claudart/config/paths.dart';
import 'package:claudart/session/handoff_event.dart';
import 'package:claudart/session/handoff_transition.dart';
import 'package:claudart/session/session_state.dart';
import 'package:test/test.dart';

import '../conformance/lifecycle_scenarios.dart';
import '../helpers/project_fixture.dart';

const _docPath = 'docs/topology/transition_matrix.md';
const _updateEnvVar = 'UPDATE_TOPOLOGY';
const _updateEnabledValue = '1';
const _gap = 'GAP';
const _neverTried = '·';

/// Legal cells no lifecycle scenario drives today. A ratchet: it may only go
/// down, to 0, as scenarios are added; a new legal move without a scenario
/// fails. It rose from 14 to 15 once, on purpose, when `tornDown` became legal
/// from three more statuses: two are driven by scenarios, the third is
/// `debugInProgress`, which no command rests in (as with its other cells).
const _knownUndrivenLegalCells = 15;

/// A logged move: the cell it landed in and whether the table rejected it.
typedef LoggedMove = ({HandoffStatus from, HandoffEvent event, bool rejected});

/// Every move logged by [scenario] run in [environment], in order.
Future<List<LoggedMove>> loggedMoves(
  LifecycleEnvironment environment,
  List<LifecycleStep> scenario,
) async {
  final io = freshLifecycleIo(environment);
  for (final step in scenario) {
    await quietly(() => step.run(io));
  }
  final raw = io.read(
    logFilePath(logsDirFor(ProjectFixture.workspace), LogFile.transitions),
  );
  return [
    for (final line in raw.split('\n').where((l) => l.isNotEmpty))
      _moveOf(jsonDecode(line) as Map<String, dynamic>),
  ];
}

LoggedMove _moveOf(Map<String, dynamic> entry) => (
      from: HandoffStatus.values.byName(
        entry[HandoffTransitionField.from.name] as String,
      ),
      event: HandoffEvent.values.byName(
        entry[HandoffTransitionField.event.name] as String,
      ),
      rejected: entry[LogEntryField.rejected.name] == true,
    );

/// Hits per cell over every scenario in the default environment.
Future<Map<(HandoffStatus, HandoffEvent), int>> hitsPerCell() async {
  final hits = <(HandoffStatus, HandoffEvent), int>{};
  for (final scenario in lifecycleScenarios().values) {
    for (final move in await loggedMoves(
      defaultLifecycleEnvironment,
      scenario,
    )) {
      final cell = (move.from, move.event);
      hits[cell] = (hits[cell] ?? 0) + 1;
    }
  }
  return hits;
}

/// The legal cells in [hits] that no scenario made.
int undrivenLegalCells(Map<(HandoffStatus, HandoffEvent), int> hits) => [
      for (final from in HandoffStatus.values)
        for (final event in HandoffEvent.values)
          if (from.after(event) != null && (hits[(from, event)] ?? 0) == 0)
            (from, event),
    ].length;

String cellOf(HandoffStatus from, HandoffEvent event, int hits) {
  final legal = from.after(event) != null;
  if (legal) return hits > 0 ? 'ok x$hits' : _gap;
  return hits > 0 ? 'REJ x$hits' : _neverTried;
}

String _cell(
  Map<(HandoffStatus, HandoffEvent), int> hits,
  HandoffStatus from,
  HandoffEvent event,
) =>
    cellOf(from, event, hits[(from, event)] ?? 0);

String renderTransitionMatrix(Map<(HandoffStatus, HandoffEvent), int> hits) {
  final gaps = [
    for (final from in HandoffStatus.values)
      for (final event in HandoffEvent.values)
        if (from.after(event) != null && (hits[(from, event)] ?? 0) == 0)
          '- `${from.name}` --`${event.name}`--> '
              '`${from.after(event)!.name}`',
  ];
  final rejected = [
    for (final entry in hits.entries)
      if (entry.key.$1.after(entry.key.$2) == null)
        '- `${entry.key.$1.name}` --`${entry.key.$2.name}`-- x${entry.value}',
  ];
  return [
    '# Transition matrix',
    '',
    '> Generated by `make topology` from the code. Do not edit by hand: a '
        'test fails when this file and the code disagree.',
    '',
    'Each cell is what the real lifecycle scenarios did '
        '(`test/conformance/lifecycle_scenarios.dart`): `ok xN` the move is '
        'in the table and a command made it N times; `$_gap` the table allows '
        'it and no scenario drives it; `REJ xN` a command tried a move the '
        'table lacks; `$_neverTried` forbidden and not tried.',
    '',
    '| status \\ event | '
        '${HandoffEvent.values.map((e) => e.name).join(' | ')} |',
    '|${'---|' * (HandoffEvent.values.length + 1)}',
    for (final from in HandoffStatus.values)
      '| ${from.name} | '
          '${[
            for (final event in HandoffEvent.values) _cell(hits, from, event),
          ].join(' | ')} |',
    '',
    '## Legal moves no scenario drives (${gaps.length})',
    '',
    if (gaps.isEmpty) '—' else ...gaps,
    '',
    '## Moves a command tried that the table rejects',
    '',
    if (rejected.isEmpty) '—' else ...rejected,
    '',
  ].join('\n');
}

void main() {
  group('the logged moves', () {
    for (final scenario in lifecycleScenarios().entries) {
      test('${scenario.key}: identical in every environment', () async {
        final reference = await loggedMoves(
          defaultLifecycleEnvironment,
          scenario.value,
        );
        for (final environment in lifecycleEnvironments()) {
          expect(
            await loggedMoves(environment, scenario.value),
            reference,
            reason: describeEnvironment(environment),
          );
        }
      });
    }
  });

  group('cellOf', () {
    const legal = (
      from: HandoffStatus.noHandoff,
      event: HandoffEvent.setup,
    );
    const forbidden = (
      from: HandoffStatus.readyForDebug,
      event: HandoffEvent.setup,
    );

    test('a legal move that was made', () {
      expect(cellOf(legal.from, legal.event, 2), 'ok x2');
    });

    test('a legal move nothing makes is a gap', () {
      expect(cellOf(legal.from, legal.event, 0), _gap);
    });

    test('a forbidden move that was tried is rejected', () {
      expect(cellOf(forbidden.from, forbidden.event, 1), 'REJ x1');
    });

    test('a forbidden move not tried is quiet', () {
      expect(cellOf(forbidden.from, forbidden.event, 0), _neverTried);
    });
  });

  group('the ratchet', () {
    test('legal cells no scenario drives do not grow', () async {
      expect(
        undrivenLegalCells(await hitsPerCell()),
        lessThanOrEqualTo(_knownUndrivenLegalCells),
        reason: 'A legal move has no lifecycle scenario. Add one, then '
            'lower _knownUndrivenLegalCells.',
      );
    });
  });

  group('the checked-in doc', () {
    test('docs/topology/transition_matrix.md matches the code', () async {
      final rendered = renderTransitionMatrix(await hitsPerCell());
      if (Platform.environment[_updateEnvVar] == _updateEnabledValue) {
        File(_docPath)
          ..createSync(recursive: true)
          ..writeAsStringSync(rendered);
      }
      expect(
        File(_docPath).readAsStringSync(),
        rendered,
        reason: 'The commands or the table changed: run `make topology` and '
            'review the diff.',
      );
    });
  });
}
