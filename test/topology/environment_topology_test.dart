// environment_topology_test.dart — the generated environments doc, and proof
// it is current.
//
// docs/topology/environments.md is rendered from the code: ClaudartCommand's
// getters, the surface / run-mode / link-state enums, and which files read
// dartrix. It fails when the code and the checked-in doc disagree:
//
//   make topology        # UPDATE_TOPOLOGY=1 rewrites the doc

import 'dart:io';

import 'package:claudart/commands/claudart_command.dart';
import 'package:claudart/paths.dart';
import 'package:claudart/pipeline/claudart_surface.dart';
import 'package:claudart/session/run_mode.dart';
import 'package:claudart/workspace/workspace_link_state.dart';
import 'package:test/test.dart';

import '../helpers/event_usage.dart';
import '../helpers/variant_topology.dart';

const _docPath = 'docs/topology/environments.md';
const _updateEnvVar = 'UPDATE_TOPOLOGY';
const _updateEnabledValue = '1';
const _generatedConst = 'dependency_config.g.dart';
const _noReader = '— no reader yet';

/// Files (other than generated ones and the codegen itself) that read the
/// project's dartrix usage: they mention `usesDartrix` or
/// `detectsDartrixDependency`.
List<String> dartrixReaders(Map<String, String> sources) => [
      for (final entry in sources.entries)
        if (!entry.key.startsWith('lib/generated/') &&
            !entry.key.startsWith('lib/codegen/') &&
            (entry.value.contains('usesDartrix') ||
                entry.value.contains('detectsDartrixDependency')))
          entry.key,
    ]..sort();

/// Files that import the generated dependency-config const.
List<String> generatedConstReaders(Map<String, String> sources) => [
      for (final entry in sources.entries)
        if (!entry.key.startsWith('lib/generated/') &&
            entry.value.contains("import '") &&
            RegExp("import '[^']*$_generatedConst'").hasMatch(entry.value))
          entry.key,
    ]..sort();

String _list(Iterable<String> items) => items.isEmpty ? '—' : items.join(', ');

String renderEnvironmentTopology(Map<String, String> sources) {
  final readers = dartrixReaders(sources);
  final constReaders = generatedConstReaders(sources);
  return [
    '# Environments and surfaces',
    '',
    '> Generated by `make topology` from the code. Do not edit by hand: a '
        'test fails when this file and the code disagree.',
    '',
    '## Commands',
    '',
    'Where each command can be started, whether it takes `--headless`, and '
        'which handoff events it passes. Declared on `ClaudartCommand` and '
        'checked against the sources by `claudart_command_test.dart`.',
    '',
    renderTopology<ClaudartCommand>(ClaudartCommand.values, {
      'entry points': (c) => _list(c.reachedFrom.map((e) => e.name)),
      'headless': (c) => c.supportsHeadless,
      'handoff events': (c) => _list(c.handoffEvents.map((e) => e.name)),
    }),
    '',
    '## Surfaces',
    '',
    'How the pipeline renders. zedup\'s TUI is the `tui` surface: it runs the '
        'pipelines itself and shells out to `claudart status` and `setup`. '
        '`make consumer-check` replays claudart\'s lifecycle against zedup\'s '
        'real reader.',
    '',
    renderTopology<ClaudartSurface>(ClaudartSurface.values, {
      'label': (s) => s.label,
      'uses stdout': (s) => s.usesStdout,
    }),
    '',
    '## Run modes',
    '',
    renderTopology<RunMode>(RunMode.values, {
      'asks a human': (m) => m == RunMode.interactive,
    }),
    '',
    '## Workspace link states',
    '',
    '`claudart link` points the project\'s IDE directories at the workspace '
        'copy. `linkStateOf` reads the state from the filesystem.',
    '',
    renderTopology<WorkspaceLinkState>(WorkspaceLinkState.values, {
      'linked': (s) => s.isLinked,
    }),
    '',
    renderTopology<IdeIntegration>(IdeIntegration.values, {
      'directory': (i) => i.dirName,
    }),
    '',
    '## dartrix',
    '',
    'A project "uses dartrix" when its pubspec declares it. Files that read '
        'that today:',
    '',
    _list(readers.map((f) => '`$f`')),
    '',
    'Files that read the generated `$_generatedConst` constant: '
        '${constReaders.isEmpty ? _noReader : _list(constReaders)}. '
        '(`claudart link` regenerates it; nothing branches on it yet.)',
    '',
  ].join('\n');
}

void main() {
  group('dartrixReaders', () {
    final readers = dartrixReaders({
      'lib/commands/add.dart': 'final x = detectsDartrixDependency(p);',
      'lib/templates/plan.dart': 'bool usesDartrix = false;',
      'lib/generated/dependency_config.g.dart':
          'const bool usesDartrix = true;',
      'lib/codegen/gen.dart': 'render({required bool usesDartrix})',
      'lib/other.dart': 'nothing here',
    });

    test('lists files that mention dartrix usage, sorted', () {
      expect(readers, ['lib/commands/add.dart', 'lib/templates/plan.dart']);
    });

    test('ignores the generated const and the codegen that writes it', () {
      expect(
          readers, isNot(contains('lib/generated/dependency_config.g.dart')));
      expect(readers, isNot(contains('lib/codegen/gen.dart')));
    });
  });

  group('generatedConstReaders', () {
    test('finds files importing the generated const', () {
      final readers = generatedConstReaders({
        'lib/a.dart': "import 'generated/$_generatedConst';",
        'lib/b.dart': "import 'other.dart';",
        'lib/generated/$_generatedConst': 'const bool usesDartrix = true;',
      });
      expect(readers, ['lib/a.dart']);
    });

    test('is empty when nothing imports it', () {
      expect(
          generatedConstReaders({'lib/b.dart': "import 'x.dart';"}), isEmpty);
    });
  });

  group('the checked-in doc', () {
    test('docs/topology/environments.md matches the code', () {
      final rendered = renderEnvironmentTopology(readLibSources());
      if (Platform.environment[_updateEnvVar] == _updateEnabledValue) {
        File(_docPath)
          ..createSync(recursive: true)
          ..writeAsStringSync(rendered);
      }
      expect(
        File(_docPath).readAsStringSync(),
        rendered,
        reason: 'The commands or their environments changed: run '
            '`make topology` and review the diff.',
      );
    });
  });
}
