// model_metadata_topology_test.dart — the topology of model metadata, and the
// proof it has no dead and no duplicated facts.
//
// docs/topology/model_metadata.md is rendered from the code: the declared
// facts (AgentModel), the observed fields (ModelObservationField), which files
// read each declared fact, and what the one real captured run drifts on. The
// tests fail when
//   - a declared fact has no reader (a field nothing uses),
//   - a model id is spelled out anywhere in lib/ but agent_model.dart
//     (a second source of truth),
//   - or the checked-in doc and the code disagree.
//
//   make topology        # UPDATE_TOPOLOGY=1 rewrites the doc

import 'dart:convert';
import 'dart:io';

import 'package:claudart/pipeline/agent_model.dart';
import 'package:claudart/pipeline/model_observation.dart';
import 'package:test/test.dart';

import '../helpers/event_usage.dart';
import '../helpers/variant_topology.dart';

const _docPath = 'docs/topology/model_metadata.md';
const _fixturePath = 'test/fixtures/claude_result_line_haiku.json';
const _updateEnvVar = 'UPDATE_TOPOLOGY';
const _updateEnabledValue = '1';
const _declaringFile = 'lib/pipeline/agent_model.dart';
const _noReader = '— no reader';

/// The declared facts a consumer can read, and how a read of each is spelled.
/// `slug` is read through `AgentModel.fromSlug`; the other two directly. A
/// mention as `ModelObservationField.<name>` is an enum variant, not a read.
enum DeclaredFact {
  slug(readPattern: r'AgentModel\.fromSlug\('),
  contextWindow(readPattern: r'(?<!ModelObservationField)\??\.contextWindow\b'),
  maxOutputTokens(
    readPattern: r'(?<!ModelObservationField)\??\.maxOutputTokens\b',
  );

  const DeclaredFact({required this.readPattern});

  final String readPattern;
}

/// Declared fact -> lib files (sorted) that read it, other than the file that
/// declares it.
Map<DeclaredFact, List<String>> readersByFact(Map<String, String> sources) => {
      for (final fact in DeclaredFact.values)
        fact: [
          for (final entry in sources.entries)
            if (entry.key != _declaringFile &&
                RegExp(fact.readPattern).hasMatch(entry.value))
              entry.key,
        ]..sort(),
    };

/// lib files other than [_declaringFile] that spell out a model id as a string
/// literal: each would be a second declaration of the same fact.
List<String> modelIdLiteralFiles(Map<String, String> sources) => [
      for (final entry in sources.entries)
        if (entry.key != _declaringFile &&
            RegExp('[\'"]claude-').hasMatch(entry.value))
          entry.key,
    ]..sort();

String _readerRows(Map<DeclaredFact, List<String>> readers) => [
      '| declared fact | read by |',
      '|---|---|',
      for (final entry in readers.entries)
        '| ${entry.key.name} | '
            '${entry.value.isEmpty ? _noReader : entry.value.join(', ')} |',
    ].join('\n');

String _capturedDrift() {
  final line = jsonDecode(File(_fixturePath).readAsStringSync())
      as Map<String, dynamic>;
  final observed = parseModelUsage(line['modelUsage']).single;
  final reconciliation = reconcileModel(
    intended: AgentModel.haiku,
    observation: observed,
  );
  final drift = reconciliation.drift.map((kind) => kind.name).toList()..sort();
  return [
    '| observed id | declared as | window (declared / observed) | '
        'output cap (declared / observed) | drift |',
    '|---|---|---|---|---|',
    '| ${observed.observedModelId} | ${reconciliation.resolved?.name} | '
        '${reconciliation.resolved?.contextWindow} / '
        '${observed.observedContextWindow} | '
        '${reconciliation.resolved?.maxOutputTokens} / '
        '${observed.observedMaxOutputTokens} | ${drift.join(', ')} |',
  ].join('\n');
}

String renderModelMetadataTopology(Map<String, String> sources) => [
      '# Model metadata topology',
      '',
      '> Generated by `make topology` from the code. Do not edit by hand: '
          'a test fails when this file and the code disagree.',
      '',
      'Three kinds of model information (docs/design.md 9.6): **declared** '
          '(`AgentModel`, below), **resolved** (the machine\'s alias mapping, '
          're-read at launch) and **observed** (the `claude` stream, per step). '
          'Observation is read from the final `result` line claudart already '
          'parses, so it costs no model call and no prompt tokens.',
      '',
      '## Declared (`AgentModel`)',
      '',
      renderTopology<AgentModel>(AgentModel.values, {
        'alias': (m) => m.alias,
        'slug': (m) => m.slug,
        'shortName': (m) => m.shortName,
        'contextWindow': (m) => m.contextWindow,
        'maxOutputTokens': (m) => m.maxOutputTokens,
        'tier': (m) => m.tier.name,
      }),
      '',
      '## Who reads each declared fact',
      '',
      'A fact with "$_noReader" is dead; a test fails on one. `slug` is read '
          'through `AgentModel.fromSlug` (observed id to declared model).',
      '',
      _readerRows(readersByFact(sources)),
      '',
      '## Observed (`ModelObservationField`)',
      '',
      'Read from `modelUsage[<observed id>]` in the result line; the id is the '
          'map key.',
      '',
      renderTopology<ModelObservationField>(ModelObservationField.values, {
        'jsonKey': (f) => f.jsonKey,
        'streamKey': (f) => f.streamKey ?? '(the map key)',
      }),
      '',
      '## Drift kinds (`reconcileModel`)',
      '',
      ModelDriftKind.values.map((kind) => '- `${kind.name}`').join('\n'),
      '',
      '## What the one captured real run drifts on',
      '',
      'From `$_fixturePath`, a real `claude -p --model haiku '
          '--output-format stream-json --verbose` run. A drift is data about '
          'the machine, not a failure.',
      '',
      _capturedDrift(),
      '',
      '## Where observations are used',
      '',
      'lib files that mention `ModelObservation`, other than its own file.',
      '',
      [
        for (final file in ([
          for (final entry in sources.entries)
            if (entry.key != 'lib/pipeline/model_observation.dart' &&
                entry.value.contains('ModelObservation'))
              entry.key,
        ]..sort()))
          '- $file',
      ].join('\n'),
      '',
    ].join('\n');

void main() {
  group('readersByFact', () {
    final readers = readersByFact({
      _declaringFile: 'int get contextWindow => 1; x.contextWindow',
      'lib/a.dart': 'final w = model.contextWindow;',
      'lib/b.dart': 'resolved?.maxOutputTokens',
      'lib/c.dart': 'ModelObservationField.contextWindow.jsonKey',
      'lib/d.dart': 'AgentModel.fromSlug(id)',
    });

    test('counts a direct read of the field', () {
      expect(readers[DeclaredFact.contextWindow], ['lib/a.dart']);
    });

    test('counts a null-aware read', () {
      expect(readers[DeclaredFact.maxOutputTokens], ['lib/b.dart']);
    });

    test('counts slug as read through fromSlug', () {
      expect(readers[DeclaredFact.slug], ['lib/d.dart']);
    });

    test('ignores the declaring file and enum-variant mentions', () {
      expect(readers[DeclaredFact.contextWindow], isNot(contains(_declaringFile)));
      expect(readers[DeclaredFact.contextWindow], isNot(contains('lib/c.dart')));
    });
  });

  group('modelIdLiteralFiles', () {
    test('flags a file that spells a model id, not the declaring file', () {
      expect(
        modelIdLiteralFiles({
          _declaringFile: "slug: 'claude-haiku-4-5-20251001'",
          'lib/x.dart': "const id = 'claude-haiku-4-5-20251001';",
          'lib/y.dart': '// claude-haiku in a comment',
        }),
        ['lib/x.dart'],
      );
    });
  });

  group('the proof, on the real lib/', () {
    final sources = readLibSources();

    for (final fact in DeclaredFact.values) {
      test('declared fact ${fact.name} has a reader', () {
        expect(
          readersByFact(sources)[fact],
          isNotEmpty,
          reason: '`${fact.name}` is declared on AgentModel but nothing reads '
              'it. Read it (reconcileModel) or remove it.',
        );
      });
    }

    test('no lib file but agent_model.dart spells out a model id', () {
      expect(modelIdLiteralFiles(sources), isEmpty);
    });

    test('each AgentModel slug is unique', () {
      final slugs = AgentModel.values.map((m) => m.slug);
      expect(slugs.toSet().length, AgentModel.values.length);
    });
  });

  group('the checked-in doc', () {
    test('docs/topology/model_metadata.md matches the code', () {
      final rendered = renderModelMetadataTopology(readLibSources());
      if (Platform.environment[_updateEnvVar] == _updateEnabledValue) {
        File(_docPath)
          ..createSync(recursive: true)
          ..writeAsStringSync(rendered);
      }
      expect(
        File(_docPath).readAsStringSync(),
        rendered,
        reason: 'Model metadata or its readers changed: run `make topology` '
            'and review the diff.',
      );
    });
  });
}
