// handoff_topology_test.dart — the generated topology doc, and proof it is
// current.
//
// docs/topology/handoff_status.md is rendered from the code
// (HandoffStatus.after, its getters, and which files pass each HandoffEvent).
// This test fails when the code and the checked-in doc disagree, so a change
// to the state machine or to who calls it cannot land without the diagram
// being regenerated:
//
//   make topology        # UPDATE_TOPOLOGY=1 rewrites the doc
//
// Expected values elsewhere come from variant getters (helpers/
// variant_topology.dart); this is the same data, drawn.

import 'dart:io';

import 'package:claudart/session/handoff_event.dart';
import 'package:claudart/session/session_state.dart';
import 'package:test/test.dart';

import '../helpers/variant_topology.dart';

const _docPath = 'docs/topology/handoff_status.md';
const _updateEnvVar = 'UPDATE_TOPOLOGY';
const _updateEnabledValue = '1';
const _libDir = 'lib';

/// The files that define the table itself; mentions there are not callers.
const _tableFiles = {
  'lib/session/handoff_event.dart',
  'lib/session/session_state.dart',
};

final _eventMention = RegExp(r'HandoffEvent\.(\w+)');

/// Event -> files (relative paths, sorted) that mention it, ignoring the
/// files that define the table.
Map<HandoffEvent, List<String>> usageByEvent(Map<String, String> sources) {
  final byName = {for (final event in HandoffEvent.values) event.name: event};
  final used = <HandoffEvent, Set<String>>{
    for (final event in HandoffEvent.values) event: {},
  };
  for (final entry in sources.entries) {
    if (_tableFiles.contains(entry.key)) continue;
    for (final match in _eventMention.allMatches(entry.value)) {
      final event = byName[match.group(1)];
      if (event != null) used[event]!.add(entry.key);
    }
  }
  return {
    for (final event in HandoffEvent.values)
      event: used[event]!.toList()..sort(),
  };
}

/// Mermaid state diagram of every move `after` allows; events that share the
/// same from/to edge share one labelled arrow.
String renderStateDiagram() {
  final edges = <(HandoffStatus, HandoffStatus), List<String>>{};
  for (final from in HandoffStatus.values) {
    for (final event in HandoffEvent.values) {
      final to = from.after(event);
      if (to != null) edges.putIfAbsent((from, to), () => []).add(event.name);
    }
  }
  return [
    '```mermaid',
    'stateDiagram-v2',
    for (final edge in edges.entries)
      '  ${edge.key.$1.name} --> ${edge.key.$2.name}: ${edge.value.join(', ')}',
    '```',
  ].join('\n');
}

const _noCaller = '— no code caller';
const _promptDirs = ['lib/templates/', 'lib/pipeline/flows/'];
final _statusMention = RegExp(r'HandoffStatus\.(\w+)\.value');

String renderUsageTable(Map<HandoffEvent, List<String>> usage) {
  final rows = [
    for (final entry in usage.entries)
      '| ${entry.key.name} | '
          '${entry.value.isEmpty ? _noCaller : entry.value.join(', ')} |',
  ];
  return ['| event | passed by |', '|---|---|', ...rows].join('\n');
}

/// Prompt file -> the statuses it names through the enum, sorted by name.
/// Agents move a handoff by editing handoff.md as these prompts instruct.
Map<String, List<String>> statusMentionsByFile(Map<String, String> sources) {
  final variants = {for (final s in HandoffStatus.values) s.name};
  final result = <String, List<String>>{};
  for (final entry in sources.entries) {
    if (!_promptDirs.any(entry.key.startsWith)) continue;
    final names = {
      for (final m in _statusMention.allMatches(entry.value))
        if (variants.contains(m.group(1))) m.group(1)!,
    }.toList()
      ..sort();
    if (names.isNotEmpty) result[entry.key] = names;
  }
  return Map.fromEntries(
    result.entries.toList()..sort((a, b) => a.key.compareTo(b.key)),
  );
}

String renderPromptTable(Map<String, List<String>> mentions) => [
      '| prompt | statuses it names |',
      '|---|---|',
      for (final entry in mentions.entries)
        '| ${entry.key} | ${entry.value.join(', ')} |',
    ].join('\n');

String renderHandoffTopology(Map<String, String> sources) => [
      '# HandoffStatus topology',
      '',
      '> Generated by `make topology` from the code. Do not edit by hand: '
          'a test fails when this file and the code disagree.',
      '',
      '## Moves (`HandoffStatus.after`)',
      '',
      renderStateDiagram(),
      '',
      '## What each status answers',
      '',
      renderTopology<HandoffStatus>(HandoffStatus.values, {
        'value': (s) => s.value,
        'isPersisted': (s) => s.isPersisted,
        'canStartDebug': (s) => s.canStartDebug,
        'expectsSuggest': (s) => s.expectsSuggest,
        'expectsDebug': (s) => s.expectsDebug,
      }),
      '',
      '## Where each event is passed',
      '',
      'Files in `lib/` that mention the event, other than the table itself. '
          '"$_noCaller" is wiring still to do.',
      '',
      renderUsageTable(usageByEvent(sources)),
      '',
      '## Statuses named in agent prompts',
      '',
      'Agents move a handoff by editing `handoff.md` as these prompts '
          'instruct, so a move with "$_noCaller" above is made there. Each '
          'prompt names statuses through `HandoffStatus`, never as typed '
          'text (a test fails otherwise).',
      '',
      renderPromptTable(statusMentionsByFile(sources)),
      '',
      '## After a reset',
      '',
      '`kill`, `teardown` and an empty `rotate` leave the blank handoff, '
          'whose Status line still reads '
          '`${HandoffStatus.suggestInvestigating.value}` '
          'with no active content. `SessionState.effectiveStatus` reads it as '
          '`${HandoffStatus.noHandoff.name}`: that is what consumers should '
          'show and what `transitions.jsonl` logs. Show a session from '
          '`effectiveStatus`, never from the raw Status line. '
          '`make consumer-check` replays the lifecycle against zedup\'s real '
          'reader to prove it does.',
      '',
      '## Where it is logged',
      '',
      'Every applied move is appended to `<workspace>/logs/transitions.jsonl` '
          'as `{ts, command, from, event, to}` (enum names). A rejected move '
          'throws `InvalidHandoffTransitionException` and is logged by the '
          'central error handler.',
      '',
    ].join('\n');

Map<String, String> _readLibSources() => {
      for (final file in Directory(_libDir)
          .listSync(recursive: true)
          .whereType<File>()
          .where((f) => f.path.endsWith('.dart')))
        file.path: file.readAsStringSync(),
    };

void main() {
  group('usageByEvent', () {
    final sources = {
      'lib/commands/a.dart': 'x HandoffEvent.setup; HandoffEvent.setup;',
      'lib/commands/b.dart': 'HandoffEvent.setup and HandoffEvent.rotated',
      'lib/session/session_state.dart': 'HandoffEvent.killed',
      'lib/session/handoff_event.dart': 'HandoffEvent.tornDown',
      'lib/other.dart': 'HandoffEvent.notAnEvent',
    };
    final usage = usageByEvent(sources);

    test('lists each calling file once, sorted', () {
      expect(
        usage[HandoffEvent.setup],
        ['lib/commands/a.dart', 'lib/commands/b.dart'],
      );
    });

    test('ignores the files that define the table', () {
      expect(usage[HandoffEvent.killed], isEmpty);
      expect(usage[HandoffEvent.tornDown], isEmpty);
    });

    test('ignores names that are not events', () {
      expect(usage.values.expand((files) => files),
          isNot(contains('lib/other.dart')));
    });

    test('has an entry for every event, empty when nothing passes it', () {
      expect(usage.keys, HandoffEvent.values);
      expect(usage[HandoffEvent.debugBlocked], isEmpty);
    });
  });

  group('statusMentionsByFile', () {
    final mentions = statusMentionsByFile({
      'lib/templates/a.dart': '\${HandoffStatus.readyForDebug.value} and '
          '\${HandoffStatus.needsSuggest.value} and '
          '\${HandoffStatus.readyForDebug.value}',
      'lib/pipeline/flows/b.dart': '\${HandoffStatus.debugComplete.value}',
      'lib/commands/c.dart': '\${HandoffStatus.readyForDebug.value}',
      'lib/templates/d.dart': 'no statuses here',
      'lib/templates/e.dart': '\${HandoffStatus.notAVariant.value}',
    });

    test('lists each status once per prompt file, sorted by name', () {
      expect(
          mentions['lib/templates/a.dart'], ['needsSuggest', 'readyForDebug']);
    });

    test('covers flow prompts as well as templates', () {
      expect(mentions['lib/pipeline/flows/b.dart'], ['debugComplete']);
    });

    test('ignores files outside the prompt directories', () {
      expect(mentions, isNot(contains('lib/commands/c.dart')));
    });

    test('omits files that name no status, and names that are no variant', () {
      expect(mentions.keys, [
        'lib/pipeline/flows/b.dart',
        'lib/templates/a.dart',
      ]);
    });
  });

  group('renderStateDiagram', () {
    final diagram = renderStateDiagram();

    test('is a mermaid stateDiagram-v2 block', () {
      final lines = diagram.split('\n');
      expect(lines.first, '```mermaid');
      expect(lines[1], 'stateDiagram-v2');
      expect(lines.last, '```');
    });

    test('draws a move the table allows, with its event as the label', () {
      expect(diagram, contains('  noHandoff --> suggestInvestigating: setup'));
    });

    test('merges events that share an edge into one arrow', () {
      expect(
        diagram,
        contains(
          'suggestInvestigating --> suggestInvestigating: '
          'saveUnconfirmed, rotated',
        ),
      );
      expect(
        diagram,
        contains('readyForDebug --> readyForDebug: saveConfirmedReady'),
      );
    });

    test('draws nothing for a move the table rejects', () {
      expect(diagram, isNot(contains('debugComplete --> debugInProgress')));
    });
  });

  group('the checked-in doc', () {
    test('docs/topology/handoff_status.md matches the code', () {
      final rendered = renderHandoffTopology(_readLibSources());
      if (Platform.environment[_updateEnvVar] == _updateEnabledValue) {
        File(_docPath)
          ..createSync(recursive: true)
          ..writeAsStringSync(rendered);
      }
      expect(
        File(_docPath).readAsStringSync(),
        rendered,
        reason: 'The state machine or its callers changed: run `make topology` '
            'and review the diagram diff.',
      );
    });
  });
}
