import 'package:test/test.dart';
import 'package:path/path.dart' as p;
import 'package:claudart/commands/link.dart';
import 'package:claudart/codegen/artifact_state.dart';
import 'package:claudart/codegen/claudart_artifact.dart';
import 'package:claudart/codegen/dependency_config_codegen.dart';
import 'package:claudart/paths.dart';
import 'package:claudart/registry.dart';
import 'package:claudart/templates/claude_settings_template.dart';
import 'package:claudart/templates/claude_template.dart' show generatedMarker;
import '../helpers/mocks.dart';

const _projectRoot = '/projects/my-app';
const _projectName = 'my-app';

Never _throwExit(int code) => throw _ExitException(code);

class _ExitException implements Exception {
  final int code;
  const _ExitException(this.code);
}

String get _workspace => workspaceFor(_projectName);

/// Links `_projectRoot` for real (through `runLink`), the same fixture used
/// by `link_test.dart` — the only reliable way to get a true "freshly
/// linked" baseline to assert staleness against.
Future<MemoryFileIO> _linked() async {
  final io = MemoryFileIO(files: {
    p.join(_projectRoot, 'pubspec.yaml'): 'name: $_projectName\n',
  });
  await runLink(
    [_projectName],
    io: io,
    projectRootOverride: _projectRoot,
    confirmFn: (_) => false,
    exitFn: _throwExit,
  );
  return io;
}

/// The artifact's state as `doctor` asks it: the registry entry, when there is
/// one, answers whether the debug trace is permitted.
ArtifactState _state(
  ClaudartArtifact artifact,
  MemoryFileIO io, {
  bool? permitsDebugTrace,
}) =>
    stateOf(
      artifact,
      projectRoot: _projectRoot,
      workspace: _workspace,
      projectName: _projectName,
      permitsDebugTrace: permitsDebugTrace ??
          Registry.load(io: io)
              .findByProjectRoot(_projectRoot)
              ?.permitsDebugTrace ??
          true,
      io: io,
    );

void main() {
  group('ArtifactState.commandTemplates', () {
    test('missing when nothing was ever linked', () {
      final io = MemoryFileIO();
      expect(_state(ClaudartArtifact.commandTemplates, io), ArtifactState.missing);
    });

    test('stale when a command file was hand-edited', () async {
      final io = await _linked();
      final commandsDir = claudeCommandsDirFor(_workspace);
      final anyFile = io.files.keys.firstWhere((k) => k.startsWith('$commandsDir/'));
      io.write(anyFile, 'hand-edited, not the real template');
      expect(_state(ClaudartArtifact.commandTemplates, io), ArtifactState.stale);
    });

    test('fresh immediately after link', () async {
      final io = await _linked();
      expect(_state(ClaudartArtifact.commandTemplates, io), ArtifactState.fresh);
    });
  });

  group('ArtifactState.claudeMdTail', () {
    test('missing when CLAUDE.md does not exist', () {
      final io = MemoryFileIO();
      expect(_state(ClaudartArtifact.claudeMdTail, io), ArtifactState.missing);
    });

    test('missing when CLAUDE.md exists but has no generated marker', () {
      final io = MemoryFileIO(files: {
        claudeMdPathFor(_projectRoot): '# CLAUDE.md\n\nhand-written only.',
      });
      expect(_state(ClaudartArtifact.claudeMdTail, io), ArtifactState.missing);
    });

    test('stale when the generated tail was hand-edited', () async {
      final io = await _linked();
      final path = claudeMdPathFor(_projectRoot);
      final match = generatedMarker.firstMatch(io.read(path))!;
      io.write(path, '${io.read(path).substring(0, match.start)}## Generated by claudart link\nhand-edited.');
      expect(_state(ClaudartArtifact.claudeMdTail, io), ArtifactState.stale);
    });

    test('fresh immediately after link', () async {
      final io = await _linked();
      expect(_state(ClaudartArtifact.claudeMdTail, io), ArtifactState.fresh);
    });
  });

  group('ArtifactState.readmeRoadmap', () {
    test('notApplicable when there is no roadmap.json', () {
      final io = MemoryFileIO();
      expect(_state(ClaudartArtifact.readmeRoadmap, io), ArtifactState.notApplicable);
    });

    test('notApplicable when roadmap.json has no rows', () {
      final io = MemoryFileIO(files: {
        p.join(_projectRoot, 'roadmap.json'): '{"rows": []}',
      });
      expect(_state(ClaudartArtifact.readmeRoadmap, io), ArtifactState.notApplicable);
    });

    test('notApplicable when README.md has no roadmap marker', () {
      final io = MemoryFileIO(files: {
        p.join(_projectRoot, 'roadmap.json'):
            '{"rows": [{"phase": "1", "scope": "core", "status": "shipped"}]}',
        p.join(_projectRoot, 'README.md'): '# my-app\n\nNo roadmap marker here.',
      });
      expect(_state(ClaudartArtifact.readmeRoadmap, io), ArtifactState.notApplicable);
    });

    test('stale when the roadmap table was hand-edited', () {
      final io = MemoryFileIO(files: {
        p.join(_projectRoot, 'roadmap.json'):
            '{"rows": [{"phase": "1", "scope": "core", "status": "shipped"}]}',
        p.join(_projectRoot, 'README.md'):
            '# my-app\n\n<!-- claudart:link:roadmap -->\nhand-edited table\n---\n',
      });
      expect(_state(ClaudartArtifact.readmeRoadmap, io), ArtifactState.stale);
    });

    test('fresh when the roadmap table matches roadmap.json', () async {
      final io = MemoryFileIO(files: {
        p.join(_projectRoot, 'pubspec.yaml'): 'name: $_projectName\n',
        p.join(_projectRoot, 'roadmap.json'):
            '{"rows": [{"phase": "1", "scope": "core", "status": "shipped"}]}',
        p.join(_projectRoot, 'README.md'):
            '# my-app\n\n<!-- claudart:link:roadmap -->\nstale placeholder\n---\n',
      });
      // Let `runLink` perform the real splice, same as production — avoids
      // hand-constructing a spliced fixture and getting whitespace wrong.
      await runLink(
        [_projectName],
        io: io,
        projectRootOverride: _projectRoot,
        confirmFn: (_) => false,
        exitFn: _throwExit,
      );
      expect(_state(ClaudartArtifact.readmeRoadmap, io), ArtifactState.fresh);
    });
  });

  group('ArtifactState.dependencyConfig', () {
    test('notApplicable when there is no pubspec.yaml', () {
      final io = MemoryFileIO();
      expect(_state(ClaudartArtifact.dependencyConfig, io), ArtifactState.notApplicable);
    });

    test('missing when pubspec.yaml exists but nothing was generated yet', () {
      final io = MemoryFileIO(files: {
        p.join(_projectRoot, 'pubspec.yaml'): 'name: my_app\n',
      });
      expect(_state(ClaudartArtifact.dependencyConfig, io), ArtifactState.missing);
    });

    test('stale when the generated file was hand-edited', () async {
      final io = await _linked();
      io.write(
        p.join(_projectRoot, kDependencyConfigGeneratedRelativePath),
        'not what the codegen would render',
      );
      expect(_state(ClaudartArtifact.dependencyConfig, io), ArtifactState.stale);
    });

    test('fresh immediately after link', () async {
      final io = await _linked();
      expect(_state(ClaudartArtifact.dependencyConfig, io), ArtifactState.fresh);
    });
  });

  group('ArtifactState.claudeSettings', () {
    String settingsPath() => claudeSettingsPathFor(_projectRoot);

    test('missing when nothing was ever linked', () {
      expect(
        _state(ClaudartArtifact.claudeSettings, MemoryFileIO()),
        ArtifactState.missing,
      );
    });

    test('stale when settings.json exists without claudart\'s hook', () {
      final io = MemoryFileIO(files: {settingsPath(): '{"permissions":{}}'});
      expect(_state(ClaudartArtifact.claudeSettings, io), ArtifactState.stale);
    });

    test('stale when settings.json is not a JSON object', () {
      final io = MemoryFileIO(files: {settingsPath(): 'not json'});
      expect(_state(ClaudartArtifact.claudeSettings, io), ArtifactState.stale);
    });

    test('stale when the hook was hand-edited', () async {
      final io = await _linked();
      io.write(
        settingsPath(),
        io.read(settingsPath()).replaceFirst('Edit|Write|MultiEdit', 'Edit'),
      );
      expect(_state(ClaudartArtifact.claudeSettings, io), ArtifactState.stale);
    });

    test('fresh immediately after link', () async {
      final io = await _linked();
      expect(_state(ClaudartArtifact.claudeSettings, io), ArtifactState.fresh);
    });

    test('a second link changes nothing', () async {
      final io = await _linked();
      final before = io.read(settingsPath());
      await runLink(
        [_projectName],
        io: io,
        projectRootOverride: _projectRoot,
        confirmFn: (_) => false,
        exitFn: _throwExit,
      );
      expect(io.read(settingsPath()), before);
    });

    test('link keeps what the user already had in settings.json', () async {
      final io = MemoryFileIO(files: {
        p.join(_projectRoot, 'pubspec.yaml'): 'name: $_projectName\n',
        settingsPath(): '{"permissions":{"allow":["Bash(ls)"]},'
            '"env":{"CLAUDART_DEBUG":"0","OTHER":"1"}}',
      });
      await runLink(
        [_projectName],
        io: io,
        projectRootOverride: _projectRoot,
        confirmFn: (_) => false,
        exitFn: _throwExit,
      );
      final written = io.read(settingsPath());
      expect(written, contains('Bash(ls)'));
      expect(written, contains('"OTHER": "1"'));
      expect(written, contains('"CLAUDART_DEBUG": "0"'));
      expect(written, contains('claudart hook pre-edit'));
    });

    Future<MemoryFileIO> linkedSensitive({String? settings}) async {
      final io = MemoryFileIO(files: {
        p.join(_projectRoot, 'pubspec.yaml'): 'name: $_projectName\n',
        if (settings != null) settingsPath(): settings,
      });
      await runLink(
        [_projectName, '--sensitive'],
        io: io,
        projectRootOverride: _projectRoot,
        confirmFn: (_) => false,
        exitFn: _throwExit,
      );
      return io;
    }

    // The trace writes full prompts to disk, so a sensitive project must not
    // have it switched on by the settings claudart writes.
    test('a sensitive project gets the hook but no debug env var', () async {
      final io = await linkedSensitive();
      final written = io.read(settingsPath());
      expect(written, contains('claudart hook pre-edit'));
      expect(written, isNot(contains('CLAUDART_DEBUG')));
      expect(_state(ClaudartArtifact.claudeSettings, io), ArtifactState.fresh);
    });

    test('link removes the debug var it set earlier from a sensitive project',
        () async {
      final io = await linkedSensitive(
        settings: '{"env":{"CLAUDART_DEBUG":"1","KEEP":"me"}}',
      );
      final written = io.read(settingsPath());
      expect(written, isNot(contains('CLAUDART_DEBUG')));
      expect(written, contains('"KEEP": "me"'));
    });

    test('settings that still carry the 1 are stale when the trace is not '
        'permitted, fresh when it is', () {
      final io = MemoryFileIO(files: {
        settingsPath(): mergeClaudeSettings('', debugTrace: true),
      });
      expect(
        _state(ClaudartArtifact.claudeSettings, io, permitsDebugTrace: false),
        ArtifactState.stale,
      );
      expect(
        _state(ClaudartArtifact.claudeSettings, io, permitsDebugTrace: true),
        ArtifactState.fresh,
      );
    });

    test('link leaves an unreadable settings.json alone', () async {
      final io = MemoryFileIO(files: {
        p.join(_projectRoot, 'pubspec.yaml'): 'name: $_projectName\n',
        settingsPath(): 'not json',
      });
      await runLink(
        [_projectName],
        io: io,
        projectRootOverride: _projectRoot,
        confirmFn: (_) => false,
        exitFn: _throwExit,
      );
      expect(io.read(settingsPath()), 'not json');
    });
  });

  group('self-hosting: a freshly linked project has no drift', () {
    // commandTemplates/claudeMdTail/dependencyConfig's own "fresh
    // immediately after link" cases above already cover this scenario per
    // artifact — this adds the one case they don't: the opt-in artifact
    // this fixture never enables.
    test('readmeRoadmap is notApplicable (this fixture never opts in)', () async {
      final io = await _linked();
      expect(_state(ClaudartArtifact.readmeRoadmap, io), ArtifactState.notApplicable);
    });
  });
}
