// report.dart — what the audit found, written from the rows it logged
//
// Reads `proofs.jsonl` rows, not the run's memory, so the report can be made
// again from the log alone. One section for each proof; for the transition
// table a grid shows, for each (status, event) cell, how many of its faults the
// named proofs caught.

import 'package:claudart/logging/logger.dart';
import 'package:claudart/session/handoff_event.dart';
import 'package:claudart/session/session_state.dart';

import 'controls.dart' show controlProof;
import 'table_faults.dart';

/// Tests that only compare the code with a document generated from it. They
/// fail when the code changes, but `make topology` makes them pass again, so
/// they are a tripwire and not a proof that the change was right.
const driftTestPrefix = 'the checked-in doc ';

bool _onlyDriftTests(Map<String, dynamic> row) {
  final names = (row[LogEntryField.caughtBy.name] as List<dynamic>).cast<String>();
  return names.isNotEmpty && names.every((name) => name.startsWith(driftTestPrefix));
}

String _field(Map<String, dynamic> row, LogEntryField field) =>
    '${row[field.name]}';

bool _is(Map<String, dynamic> row, ProofVerdict verdict, {int? tier}) =>
    row[LogEntryField.verdict.name] == verdict.name &&
    (tier == null || row[LogEntryField.tier.name] == tier);

/// The markdown report for [loggedRows], proof rows in the order they were
/// logged. A fault logged more than once (a rerun) counts by its latest row.
String renderReport(List<Map<String, dynamic>> loggedRows) {
  final latest = <String, Map<String, dynamic>>{};
  for (final row in loggedRows) {
    if (row[LogEntryField.proof.name] == controlProof) continue;
    latest['${_field(row, LogEntryField.proof)}|${_field(row, LogEntryField.fault)}'] = row;
  }
  final byProof = <String, List<Map<String, dynamic>>>{};
  for (final row in latest.values) {
    byProof.putIfAbsent(_field(row, LogEntryField.proof), () => []).add(row);
  }

  final out = StringBuffer()
    ..writeln('# Proof audit')
    ..writeln()
    ..writeln('> Generated by `make proof-audit` from the rows in `proofs.jsonl`. '
        'It takes minutes, so the test suite does not check it: rerun it after a '
        'change to a matrix or to its proofs.')
    ..writeln()
    ..writeln('Each fault changes one fact of a matrix in a scratch copy. Tier 1 is '
        'the tests meant to carry the proof; tier 2 is the wider suite, run only '
        'for a fault tier 1 missed. The control faults (a comment that changes '
        'nothing must come out missed, source that does not compile must come out '
        'invalid) ran first and are not counted here.')
    ..writeln()
    ..writeln('| Proof | Faults | Caught by the named proofs | Only by a generated doc | Only by the wider suite | Missed | Invalid |')
    ..writeln('|---|---|---|---|---|---|---|');
  for (final entry in byProof.entries) {
    final rows = entry.value;
    final tierOne = rows.where((r) => _is(r, ProofVerdict.caught, tier: 1)).toList();
    out.writeln('| ${entry.key} | ${rows.length} | ${tierOne.length} | '
        '${tierOne.where(_onlyDriftTests).length} | '
        '${rows.where((r) => _is(r, ProofVerdict.caught, tier: 2)).length} | '
        '${rows.where((r) => _is(r, ProofVerdict.missed)).length} | '
        '${rows.where((r) => _is(r, ProofVerdict.invalid)).length} |');
  }
  for (final entry in byProof.entries) {
    _renderProof(out, entry.key, entry.value);
  }
  return out.toString();
}

void _renderProof(StringBuffer out, String proof, List<Map<String, dynamic>> rows) {
  final tierOneCaught = rows.where((r) => _is(r, ProofVerdict.caught, tier: 1)).toList();
  final tierTwoCaught = rows.where((r) => _is(r, ProofVerdict.caught, tier: 2)).toList();
  final onlyDrift = tierOneCaught.where(_onlyDriftTests).toList();
  final missed = rows.where((r) => _is(r, ProofVerdict.missed)).toList();
  final invalid = rows.where((r) => _is(r, ProofVerdict.invalid)).toList();
  final repeated = rows.where((r) => (r[LogEntryField.attempts.name] ?? 1) != 1).length;

  out
    ..writeln()
    ..writeln('## $proof')
    ..writeln()
    ..writeln('| Verdict | Faults |')
    ..writeln('|---|---|')
    ..writeln('| caught by the named proofs (tier 1) | ${tierOneCaught.length} |')
    ..writeln('| of those, caught only by a generated-doc drift test: regenerating the docs hides them | ${onlyDrift.length} |')
    ..writeln('| caught only by the wider suite (tier 2): the proofs are weak here | ${tierTwoCaught.length} |')
    ..writeln('| missed by every test: a gap | ${missed.length} |')
    ..writeln('| invalid (did not compile or load): shows nothing | ${invalid.length} |')
    ..writeln('| total | ${rows.length} |')
    ..writeln('| faults whose first test run showed nothing and was repeated | $repeated |');

  final cells = <(String, String), List<Map<String, dynamic>>>{};
  for (final row in rows) {
    final match = cellFaultPattern.firstMatch(_field(row, LogEntryField.fault));
    if (match == null) continue;
    cells.putIfAbsent((match.group(1)!, match.group(2)!), () => []).add(row);
  }
  if (cells.isNotEmpty) {
    out
      ..writeln()
      ..writeln('### Cells')
      ..writeln()
      ..writeln('Faults the named proofs caught, out of all faults on that cell. '
          '`*` a tier-2 catch is among them, `!` a fault nothing caught.')
      ..writeln()
      ..writeln('| status \\ event | ${HandoffEvent.values.map((e) => e.name).join(' | ')} |')
      ..writeln('|---|${List.filled(HandoffEvent.values.length, '---').join('|')}|');
    for (final status in HandoffStatus.values) {
      final entries = [
        for (final event in HandoffEvent.values)
          () {
            final faults = cells[(status.name, event.name)] ?? const [];
            if (faults.isEmpty) return 'none';
            final caught = faults.where((r) => _is(r, ProofVerdict.caught, tier: 1)).length;
            final weak = faults.any((r) => _is(r, ProofVerdict.caught, tier: 2));
            final gap = faults.any((r) => _is(r, ProofVerdict.missed));
            return '$caught/${faults.length}${weak ? '*' : ''}${gap ? '!' : ''}';
          }(),
      ];
      out.writeln('| ${status.name} | ${entries.join(' | ')} |');
    }
  }

  void listFaults(String title, List<Map<String, dynamic>> faults) {
    out
      ..writeln()
      ..writeln('### $title')
      ..writeln();
    if (faults.isEmpty) {
      out.writeln('None.');
      return;
    }
    out
      ..writeln('| Fault | Where | Caught by |')
      ..writeln('|---|---|---|');
    for (final row in faults) {
      final by = (row[LogEntryField.caughtBy.name] as List<dynamic>).take(3).join('; ');
      out.writeln('| ${_field(row, LogEntryField.fault)} | '
          '`${_field(row, LogEntryField.sourceFile)}:${_field(row, LogEntryField.sourceLine)}` | '
          '${by.isEmpty ? 'nothing' : by} |');
    }
  }

  listFaults('Caught only by a generated-doc drift test', onlyDrift);
  listFaults('Missed by every test', missed);
  listFaults('Caught only by the wider suite', tierTwoCaught);
  listFaults('Invalid faults', invalid);

  final carried = <String, int>{};
  final independent = <String, int>{};
  for (final row in tierOneCaught) {
    final names = (row[LogEntryField.caughtBy.name] as List<dynamic>).cast<String>();
    for (final name in names) {
      carried[name] = (carried[name] ?? 0) + 1;
    }
    final others = names.where((n) => !n.startsWith(driftTestPrefix)).toSet();
    independent['${others.length >= 5 ? '5 or more' : others.length}'] =
        (independent['${others.length >= 5 ? '5 or more' : others.length}'] ?? 0) + 1;
  }
  final ranked = carried.entries.toList()..sort((a, b) => b.value.compareTo(a.value));
  out
    ..writeln()
    ..writeln('### Which tests carry the proof')
    ..writeln()
    ..writeln('Tier-1 tests that failed for at least one fault, and for how many. '
        'A proof test that appears nowhere here is not what protects this matrix.')
    ..writeln()
    ..writeln('| Test | Faults it caught |')
    ..writeln('|---|---|');
  for (final entry in ranked.take(25)) {
    out.writeln('| ${entry.key} | ${entry.value} |');
  }
  final spread = independent.entries.toList()..sort((a, b) => a.key.compareTo(b.key));
  out
    ..writeln()
    ..writeln('Faults by how many tests other than a generated-doc drift test caught '
        'them (a fault with one rests on one test): '
        '${spread.map((e) => '${e.key}: ${e.value}').join(', ')}.');
}
