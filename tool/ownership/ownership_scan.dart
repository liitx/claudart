// ownership_scan.dart — who owns which component across claudart, dartrix and
// zedup, and where tests reach into another repo's components.
//
//   dart run tool/ownership/ownership_scan.dart \
//       [claudart=PATH dartrix=PATH zedup=PATH]
//   make ownership         # writes docs/topology/ownership.md
//
// Read-only. Three questions, answered from the code:
//   1. Which public components (enum, class, sealed, abstract, mixin) does each
//      repo declare?
//   2. Which names are declared in more than one repo? (a component that should
//      have one owner)
//   3. Which tests in a repo read members of ANOTHER repo's components? Those
//      are redundant-test candidates: the owning repo already tests them.

import 'dart:io';

final _declaration = RegExp(
  r'^(?:(?:sealed|abstract|final|base|interface) )*(?:enum|class|mixin) '
  r'([A-Z]\w*)',
  multiLine: true,
);

/// Public top-level component names declared in [source].
Set<String> declaredComponents(String source) {
  // Drop line comments and string contents so a word inside them is not a
  // declaration.
  final cleaned = source
      .split('\n')
      .map((l) => l.replaceAll(RegExp(r"'[^'\n]*'"), "''"))
      .where((l) => !l.trimLeft().startsWith('//'))
      .join('\n');
  return {for (final m in _declaration.allMatches(cleaned)) m.group(1)!};
}

/// Names declared by two or more repos, with the repos that declare them
/// (sorted).
Map<String, List<String>> duplicatedComponents(
  Map<String, Set<String>> declaredByRepo,
) {
  final owners = <String, List<String>>{};
  for (final entry in declaredByRepo.entries) {
    for (final name in entry.value) {
      owners.putIfAbsent(name, () => []).add(entry.key);
    }
  }
  return {
    for (final e
        in owners.entries.toList()..sort((a, b) => a.key.compareTo(b.key)))
      if (e.value.length > 1) e.key: (e.value..sort()),
  };
}

class ForeignReference {
  const ForeignReference(
    this.file,
    this.component,
    this.reads,
    this.assertions,
    this.assertionSample,
  );

  final String file;
  final String component;

  /// Lines in [file] that read a member of [component] (a fixture, an expected
  /// value, or an assertion).
  final int reads;

  /// Of those, lines that assert the component's OWN behavior: an `expect` on a
  /// member of one of its values, or on `fromString` / `parse` / `values`. The
  /// owning repo already tests that; here it is redundant.
  final int assertions;

  /// The first such assertion line, trimmed (null when there is none).
  final String? assertionSample;
}

/// Test files in [files] (path -> source) that read a member of one of the
/// [foreign] components (`Name.member`), sorted by file then component.
List<ForeignReference> foreignTestReferences(
  Map<String, String> files,
  Set<String> foreign,
) {
  final refs = <ForeignReference>[];
  final paths = files.keys.toList()..sort();
  for (final path in paths) {
    final lines = files[path]!.split('\n');
    for (final name in foreign.toList()..sort()) {
      final read = RegExp('\\b$name\\.\\w');
      final behavior = RegExp(
        '\\b$name\\.(?:fromString|parse|values)\\b|\\b$name\\.\\w+\\.\\w',
      );
      final reads = lines.where(read.hasMatch).toList();
      if (reads.isEmpty) continue;
      final asserted = reads
          .where((l) => l.contains('expect') && behavior.hasMatch(l))
          .toList();
      refs.add(
        ForeignReference(
          path,
          name,
          reads.length,
          asserted.length,
          asserted.isEmpty ? null : asserted.first.trim(),
        ),
      );
    }
  }
  return refs;
}

// -- Reading repos and rendering ------------------------------------------

Map<String, String> _read(String root, String dir) {
  final base = Directory('$root/$dir');
  if (!base.existsSync()) return {};
  return {
    for (final f in base
        .listSync(recursive: true)
        .whereType<File>()
        .where((f) => f.path.endsWith('.dart')))
      f.path.substring(root.length + 1): f.readAsStringSync(),
  };
}

String render(Map<String, String> roots) {
  final lib = {for (final r in roots.entries) r.key: _read(r.value, 'lib')};
  final tests = {for (final r in roots.entries) r.key: _read(r.value, 'test')};
  final declared = {
    for (final r in lib.entries)
      r.key: {for (final src in r.value.values) ...declaredComponents(src)},
  };
  final dup = duplicatedComponents(declared);
  final out = StringBuffer()
    ..writeln('# Component ownership across repos')
    ..writeln()
    ..writeln('> Generated by `make ownership` from the three checkouts. Read '
        'only. A name with one owner is a unique component; a name with '
        'several is a duplicate to consolidate; a test that reads another '
        'repo\'s component is a redundant-test candidate (the owner tests it).')
    ..writeln()
    ..writeln('## Public components per repo')
    ..writeln()
    ..writeln('| repo | lib files | public components | test files |')
    ..writeln('|---|---|---|---|');
  for (final r in roots.keys) {
    out.writeln('| $r | ${lib[r]!.length} | ${declared[r]!.length} | '
        '${tests[r]!.length} |');
  }
  out
    ..writeln()
    ..writeln('## Names declared in more than one repo')
    ..writeln();
  if (dup.isEmpty) {
    out.writeln('None.');
  } else {
    out
      ..writeln('| component | declared by |')
      ..writeln('|---|---|');
    for (final e in dup.entries) {
      out.writeln('| `${e.key}` | ${e.value.join(', ')} |');
    }
  }
  out
    ..writeln()
    ..writeln("## Tests that read another repo's components")
    ..writeln();
  var anyForeign = false;
  for (final r in roots.keys) {
    final foreign = {
      for (final o in declared.entries)
        if (o.key != r) ...o.value.difference(declared[r]!),
    };
    final refs = foreignTestReferences(tests[r]!, foreign);
    if (refs.isEmpty) continue;
    anyForeign = true;
    out
      ..writeln('### $r')
      ..writeln()
      ..writeln('| test file | component | reads | asserts its behavior | '
          'first assertion |')
      ..writeln('|---|---|---|---|---|');
    for (final ref in refs) {
      final sample = ref.assertionSample;
      out.writeln('| `${ref.file}` | `${ref.component}` | ${ref.reads} | '
          '${ref.assertions} | '
          '${sample == null ? '—' : '`${sample.replaceAll('|', '\\|')}`'} |');
    }
    out.writeln();
  }
  if (!anyForeign) out.writeln('None.');
  return out.toString();
}

void main(List<String> args) {
  final here = Directory.current.path;
  final roots = {
    'claudart': here,
    'dartrix': '$here/../dartrix',
    'zedup': '$here/../zedup',
  };
  for (final arg in args) {
    final parts = arg.split('=');
    if (parts.length == 2 && roots.containsKey(parts[0])) {
      roots[parts[0]] = parts[1];
    }
  }
  roots.removeWhere((_, path) => !Directory('$path/lib').existsSync());
  stdout.write(render(roots));
}
